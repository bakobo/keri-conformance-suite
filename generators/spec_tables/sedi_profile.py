"""The sedi-1 deployment profile file, built from ``scenarios/sedi/profile.json`` and the cases that
belong to it (docs/design.md, Targets and profiles; this.i 2u40l9tk, 8g9vtxvc and 47yreej2).

A layered profile names its prerequisites, the operations and features an adapter must declare to
claim it, and the choices it makes where the specifications are silent. Each choice carries its
reading, why, what would overturn it, and the ambiguity it settles. Every assertion in the
profile's cases rests on at least one choice, and every choice must be exercised both ways, by at
least one case that a correct implementation accepts and one it refuses. While the profile's
version is draft, a choice not yet exercised both ways is listed, so the profile can be built in
steps without hiding the gap; the generator refuses to mark a version active with one.
"""

import hashlib
import json
import re

from .errors import ScenarioError

CHOICE_ID = re.compile(r"[a-z0-9][a-z0-9-]{0,63}")  # always applied with fullmatch
NID = re.compile(r"[0-9][0-9a-z]{7}")  # a this.i node id
STATUSES = ("draft", "active")
COMMIT = re.compile(r"[0-9a-f]{40}")

ABOUT = (
    "A layered, non-normative profile: SEDI's deployment profile, a version of the choices the "
    "State of Utah's SEDI program makes where the CESR, KERI and ACDC specifications are silent or "
    "disagree. Passing it is an interoperability claim, never a conformance claim, and it can be "
    "made only together with its prerequisites' conformance verdicts, from one run (docs/design.md, "
    "Targets and profiles). This file is generated by scripts/regenerate from scenarios/sedi/ and "
    "must not be edited. Fields: name; normative (false); version; status (draft until "
    "ratified); basis; prerequisites (profiles whose cases every run of this one also sends); "
    "pins (the suite version and specification commits it was built against, and the main-branch "
    "commits that draft cases cite); requires (the operations and features an adapter must "
    "declare to claim it); maxima (input bounds an implementation must hold to); choices (each "
    "with its reading, why, what would overturn it, the tick tracking the ambiguity, the this.i "
    "decision that made it, and the cases that exercise it); cases (the case ids, in order)."
)


def _text(value) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _choice_problem(choice, seen: set[str]) -> str | None:
    if not isinstance(choice, dict):
        return "a choice is not an object"
    known = {"id", "reading", "basis", "overturn", "tick", "decided", "security"}
    cid = choice.get("id")
    if not isinstance(cid, str) or not CHOICE_ID.fullmatch(cid):
        return f"the choice id {cid!r} is not lowercase letters, digits and hyphens"
    if cid in seen:
        return f"the choice {cid} is defined twice"
    seen.add(cid)
    if set(choice) - known:
        return f"the choice {cid} has unknown fields {sorted(set(choice) - known)}"
    for field in ("reading", "basis", "overturn"):
        if not _text(choice.get(field)):
            return f"the choice {cid} needs a non-empty {field}"
    if "tick" in choice and not (isinstance(choice["tick"], str)
                                 and re.fullmatch(r"[0-9a-z]{4}", choice["tick"])):
        return f"the choice {cid} names the tick {choice['tick']!r}, which is not a tick id"
    if not (isinstance(choice.get("decided"), str) and NID.fullmatch(choice["decided"])):
        return f"the choice {cid} must name the this.i decision that made it"
    if "security" in choice and choice["security"] is not True:
        return f"the choice {cid} marks security only as true"
    return None


def _source_problem(source, *, operations, features, profiles) -> str | None:
    if not isinstance(source, dict):
        return "it is not an object"
    fields = {"name", "version", "status", "basis", "prerequisites", "requires", "drafts",
              "maxima", "choices"}
    if set(source) != fields:
        return f"it must have exactly the fields {sorted(fields)}"
    if not (isinstance(source["name"], str) and CHOICE_ID.fullmatch(source["name"])):
        return f"its name {source['name']!r} is not a profile name"
    if not _text(source["version"]) or not _text(source["basis"]):
        return "its version and basis must be non-empty"
    if source["status"] not in STATUSES:
        return f"its status must be one of {', '.join(STATUSES)}"
    prerequisites = source["prerequisites"]
    if (not isinstance(prerequisites, list) or not prerequisites
            or any(not isinstance(p, str) or p not in profiles for p in prerequisites)):
        return f"its prerequisites must be a non-empty list of the profiles {sorted(profiles)}"
    requires = source["requires"]
    if not (isinstance(requires, dict) and set(requires) == {"operations", "features"}
            and all(isinstance(requires[k], list)
                    and all(isinstance(v, str) for v in requires[k]) for k in requires)):
        return "its requires must list operations and features, by name"
    unknown = [o for o in requires["operations"] if o not in operations]
    unknown += [f for f in requires["features"] if f not in features]
    if unknown:
        return f"it requires {', '.join(map(str, unknown))}, which the protocol does not define"
    drafts = source["drafts"]
    if not isinstance(drafts, dict) or not all(
            isinstance(d, dict) and set(d) == {"repository", "commit", "why"}
            and isinstance(d["commit"], str) and COMMIT.fullmatch(d["commit"])
            and _text(d["why"]) and _text(d["repository"]) for d in drafts.values()):
        return "each of its drafts must give a repository, a full commit and why"
    if not isinstance(source["maxima"], dict) or not all(
            type(v) is int and v > 0 for v in source["maxima"].values()):
        return "its maxima must map names to positive integers"
    if not isinstance(source["choices"], list) or not source["choices"]:
        return "it must make at least one choice"
    seen: set[str] = set()
    for choice in source["choices"]:
        problem = _choice_problem(choice, seen)
        if problem:
            return problem
    return None


# An issuance that must succeed accepts; one that must be refused refuses.
POLARITY = {"issued": "positive", "issue_refused": "negative", "presented": "positive",
            "present_refused": "negative"}
# Checks that guard a case on either side (a leak canary holds for a presentation and a refusal
# alike), so they exercise no choice on a side of their own.
GUARDS = ("secrets_absent",)


def _polarity(assertion: dict) -> str:
    """Whether a correct implementation's answer to the assertion accepts (positive) or refuses
    (negative). A check without a polarity cannot exercise a choice, so a new check must say."""
    if assertion["check"] == "verdict":
        return "positive" if assertion["expected"] == "valid" else "negative"
    if assertion["check"] in POLARITY:
        return POLARITY[assertion["check"]]
    raise ScenarioError(f"the check {assertion['check']} has no polarity, so a sedi case cannot "
                        "use it until sedi_profile says whether it accepts or refuses.")


def _exercised(source: dict, cases: list[dict], pins: dict) -> dict[str, dict[str, list[str]]]:
    ids = {c["id"] for c in source["choices"]}
    # A quoted basis may cite its own specification's pinned commit, or a draft commit in the
    # same repository, never another specification's.
    allowed = {spec: {pin["commit"], *(d["commit"] for d in source["drafts"].values()
                                       if d["repository"] == pin["repository"])}
               for spec, pin in pins["specs"].items()}
    matrix = {cid: {"positive": [], "negative": []} for cid in ids}
    for case in cases:
        for assertion in case["assertions"]:
            where = f"{case['id']} {assertion['id']}"
            if assertion["level"] != "INTEROP" or not assertion.get("choices"):
                raise ScenarioError(f"{where} rests on no choice: every assertion in a "
                                    f"{source['name']} case is INTEROP and names the choices it "
                                    "rests on.")
            unknown = [c for c in assertion["choices"] if c not in ids]
            if unknown:
                raise ScenarioError(f"{where} names {', '.join(unknown)}, which "
                                    f"{source['name']} does not choose.")
            basis = assertion.get("basis")
            if isinstance(basis, dict) and not (
                    isinstance(basis.get("commit"), str) and basis["commit"]
                    and any(c.startswith(basis["commit"])
                            for c in allowed.get(basis.get("spec"), ()))):
                raise ScenarioError(f"{where} quotes the {basis.get('spec')} text at "
                                    f"{basis.get('commit')}, which {source['name']} does not "
                                    "pin.")
            if assertion["check"] in GUARDS:
                continue
            polarity = _polarity(assertion)
            other = "negative" if polarity == "positive" else "positive"
            for cid in assertion["choices"]:
                # One input cannot be both accepted and refused by a correct implementation, so a
                # case exercises a choice on one side only.
                if case["id"] in matrix[cid][other]:
                    raise ScenarioError(f"{case['id']} exercises {cid} both ways; a case is "
                                        "either accepted or refused, so each side needs its "
                                        "own case.")
                if case["id"] not in matrix[cid][polarity]:
                    matrix[cid][polarity].append(case["id"])
    return matrix


def build_profile(source, cases: list[dict], *, operations, features, profiles,
                  pins: dict) -> tuple[dict, list[str]]:
    """The profile file and, for a draft, the choices not yet exercised both ways. ``cases`` are
    the generated cases whose profile is this one; ``pins`` gives the suite version and the
    pinned specifications (name -> repository and commit)."""
    problem = _source_problem(source, operations=operations, features=features,
                              profiles=profiles)
    if problem:
        raise ScenarioError(f"scenarios/sedi: the profile source is malformed: {problem}.")
    matrix = _exercised(source, cases, pins)
    unfilled = [f"{cid} has no {polarity} case" for cid in sorted(matrix)
                for polarity in ("positive", "negative") if not matrix[cid][polarity]]
    if unfilled and source["status"] == "active":
        raise ScenarioError(f"{source['name']} version {source['version']} cannot be active "
                            f"while a choice is not exercised both ways: {'; '.join(unfilled)}.")
    choices = [{**choice, "cases": {k: sorted(v) for k, v in matrix[choice["id"]].items()}}
               for choice in source["choices"]]
    doc = {
        "about": ABOUT, "name": source["name"], "normative": False,
        "version": source["version"], "status": source["status"], "basis": source["basis"],
        "prerequisites": source["prerequisites"],
        "pins": {**pins, "drafts": source["drafts"]},
        "requires": source["requires"], "maxima": source["maxima"], "choices": choices,
        "cases": sorted(c["id"] for c in cases),
    }
    return doc, unfilled


# What a released version may never change (this.i 47yreej2): its case list and prose may grow, so
# they are left out, as is each choice's list of the cases that exercise it.
FROZEN = ("name", "version", "prerequisites", "pins", "requires", "maxima")


def frozen_digest(doc: dict) -> str:
    """The digest of what a released version of the profile fixes."""
    fixed = {key: doc[key] for key in FROZEN}
    fixed["choices"] = [{k: v for k, v in c.items() if k != "cases"} for c in doc["choices"]]
    text = json.dumps(fixed, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def check_release(doc: dict, released) -> None:
    """Refuse a released version whose fixed fields changed, and a released version not marked
    active. ``released`` maps a profile name to the suite version it was released with and the
    digest of what it fixes, as recorded when it was ratified."""
    released = released if isinstance(released, dict) else {}
    for name in released:
        if name != doc["name"]:
            raise ScenarioError(f"{name} is recorded as released but is no longer generated; a "
                                "released version is never removed or renamed.")
    record = released.get(doc["name"])
    if record is None:
        return
    if doc["status"] != "active":
        raise ScenarioError(f"{doc['name']} is recorded as released, so its status must be "
                            "active.")
    if frozen_digest(doc) != record["digest"]:
        raise ScenarioError(f"{doc['name']} version {doc['version']} is released, and its "
                            "choices, prerequisites, pins, requirements or maxima changed. A "
                            "released version never changes; make a new version instead.")
