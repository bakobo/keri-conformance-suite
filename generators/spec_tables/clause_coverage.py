"""Measure which RFC 2119 keyword sentences of each pinned specification the public cases cite, and
publish the result under docs/coverage/.

    scripts/clause-coverage            write docs/coverage/ in the repository
    scripts/clause-coverage --out DIR  write it under DIR instead
    scripts/clause-coverage --check    generate into a temporary directory and compare, byte for
                                       byte, with what is committed; exit 1 and list every
                                       difference

Which texts: every (spec, commit) that a case's clause cites, each of which must be one of the
pins in spec_source.py. Each pin is reported separately, so a spec with two pinned versions gets
two parts in its report.

Keyword sentences: every sentence of a pinned text that contains an uppercase RFC 2119 / RFC 8174
keyword as a whole word (MUST, MUST NOT, REQUIRED, SHALL, SHALL NOT, SHOULD, SHOULD NOT,
RECOMMENDED, NOT RECOMMENDED, MAY, OPTIONAL). Its level is its strongest keyword: MUST for the
first five, SHOULD for the next four, MAY for MAY and OPTIONAL, which are permissions and are
reported apart from the obligations. REQUIRED preceded by "NOT " is not a keyword, because it
states the absence of an obligation; NOT RECOMMENDED is RFC 2119's SHOULD NOT and keeps its level. Headings and fenced code blocks are skipped. A table row is
one unit, because its cells are not sentences. A list item or block quote loses its marker and is
then split like any other line. Lines are never joined: the specification texts write each
paragraph on one line, and a quote is found by line (spec_source.find_quote).

The splitting heuristic: a sentence ends at ``.``, ``!`` or ``?``, optionally followed by closing
brackets, quotes or emphasis, when whitespace and then a character that can begin a sentence (an
uppercase letter, a digit, a backtick, an opening bracket, a quote or emphasis) follow. It does
not end inside inline code or a ``[[...]]`` reference, or after a listed abbreviation such as
"e.g.".

Mapping: each assertion's ``clause.quote``, and its ``inferred_from.quote`` if it has one, is found
in the pinned text its clause names and matched to the keyword sentences on its line that contain
it or that it contains. An assertion with an inference tests both quotes by inference; one without
tests its clause directly. A quote that matches no keyword sentence is listed in the report, not
refused. A sentence is covered when an active case cites it; disputed and other non-active cases
are listed but do not cover anything.

Triage: ``scenarios/<spec>/triage.json`` holds hand-kept judgments keyed by the exact sentence
text. A sentence whose text occurs more than once in a pinned text has a list of judgments, each
naming its ``section`` (the nearest heading's text, as the report shows it) and, when the text
also repeats within that section, its 1-based ``occurrence`` there; a single judgment may be
written as an object instead of a list of one. Each judgment must identify exactly one sentence
in every pinned text of its spec that contains the text: a repeated text without the
disambiguator it needs, a disambiguator that matches nothing, a disambiguator on a text that
does not need it, two judgments of one sentence, and an entry whose text is not a keyword
sentence of any pinned text of its spec are all refused, so stale triage fails loudly. A
sentence with no judgment is unassessed.

Exit status: 0 success; 1 --check found differences; 2 a specification text is unavailable; 3 an
input could not be interpreted (a malformed case or triage file, an unknown check type, an
unpinned commit, stale triage, an oversized report); 4 a report or its temporary copy could not be
read or written, with a code whose trailing r says retrying could help. Errors 2, 3 and 4 print a
coded message on standard error.
"""

