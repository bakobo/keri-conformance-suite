"""Generate every CESR and KERI case and the profiles that list them, from ``scenarios/cesr/`` and
``scenarios/keri/``.

``generate(root)`` returns the files it would write, as a mapping from repository-relative path
to exact bytes. ``scripts/regenerate`` writes them, or with ``--check`` compares them with what
is committed.
"""

