"""tools/site_source.py: definitions shown as tooltips on the results pages, and the generated
profile pages that the results matrix's column headers link to."""

import json
import re

import pytest
from conftest import ROOT
from result_docs import REPRODUCED, case, record, report, result

from keri_conformance.errors import RunnerError
from tools import site_source as S
from tools.results import Result, result_path


def loaded(*docs):
    return [Result(result_path(doc), doc) for doc in docs]


def test_a_known_value_gets_its_definition_as_a_tooltip():
    assert S.term("no-evidence") == (
        f'<abbr title="{S.html_attr(S.GLOSSARY["no-evidence"])}">no\\-evidence</abbr>')
    assert S.term("pass") == "pass"
    assert S.term("<x>") == "&lt;x&gt;"


def test_a_definition_is_safe_inside_an_attribute():
    assert S.html_attr('a "b" & <c>') == "a &quot;b&quot; &amp; &lt;c&gt;"


def test_every_glossary_entry_is_explained_on_a_page():
    pages = " ".join(p.read_text(encoding="utf-8") for p in (ROOT / "docs").glob("*.md"))
    for value in S.GLOSSARY:
        assert f"`{value}`" in pages or f"*{value}*" in pages, value


def test_verdicts_outcomes_and_labels_carry_tooltips():
    unsupported = case("CESR-0003", outcome="not-supported",
                       records=[record(outcome="not-supported")])
    rep = report([case(), unsupported])
    rep["summary"]["not_supported_active"] = ["CESR-0003"]
    pages = S.render_results(loaded(result(rep, REPRODUCED)))
    index = pages["results/index.md"]
    assert f'<abbr title="{S.html_attr(S.GLOSSARY["conformant"])}">conformant</abbr>' in index
    detail = pages["results/keripy/2.1.0.dev1/cesr-v1.0-reproduced.md"]
    assert '">not\\-supported</abbr>' in detail
    assert '">active</abbr>' in detail
    assert '">Reproduced by CI</abbr>' in index
    # A field label keeps its link and gains a definition as the link's title.
    assert re.search(r'\| \[Verdict\]\(\.\./\.\./\.\./verdicts\.md "[^"]+"\) \|', detail)
    assert "| Implementation |" in detail


PROFILES = {
    "cesr-v1.0": {"name": "cesr-v1.0", "normative": True, "about": "A profile.",
                  "spec": {"name": "Composable Event Streaming Representation (CESR)",
                           "tag": "v1.0", "commit": "0" * 40,
                           "repository": "https://github.com/trustoverip/kswg-cesr-specification"},
                  "cases": ["CESR-0001"]},
    "cesr-strict": {"name": "cesr-strict", "normative": False,
                    "about": "A non-normative profile: behaviour a careful parser shows. More.",
                    "basis": "Inference.", "cases": []},
    "keripy-1x-interop": {"name": "keripy-1x-interop", "normative": False,
                          "about": "A non-normative profile: interoperability with keripy 1.x.",
                          "basis": {"implementation": "keripy", "version": "1.2.14",
                                    "commit": "b" * 40},
                          "cases": []},
}
CASES = {"CESR-0001": {"id": "CESR-0001", "title": "Encode a <key>", "status": "active",
                       "operation": "cesr.encode"}}


def test_profile_pages_list_their_cases():
    pages = S.render_profiles(PROFILES, CASES)
    assert set(pages) == {"profiles/index.md", "profiles/cesr-v1.0.md",
                          "profiles/cesr-strict.md", "profiles/keripy-1x-interop.md"}
    page = pages["profiles/cesr-v1.0.md"]
    assert page.startswith("# cesr-v1.0\n")
    assert "kswg-cesr-specification/blob/" + "0" * 40 in page
    assert (f"| [CESR\\-0001]({S.REPO_URL}/blob/main/cases/cesr/CESR-0001.json) | "
            "Encode a &lt;key&gt; |") in page
    strict = pages["profiles/cesr-strict.md"]
    assert "non-normative" in strict and "Inference." in strict
    assert "No cases yet." in strict
    assert "keripy 1.2.14" in pages["profiles/keripy-1x-interop.md"]
    index = pages["profiles/index.md"]
    assert "[cesr-v1.0](cesr-v1.0.md)" in index and "[cesr-strict](cesr-strict.md)" in index


def test_matrix_headers_link_known_profiles_with_a_tooltip():
    index = S.render_results(loaded(result()), profiles=PROFILES)["results/index.md"]
    assert re.search(r'\| \[cesr\\-v1\\\.0\]\(\.\./profiles/cesr-v1\.0\.md "Cases citing [^"]+"\) \|',
                     index)
    unknown = S.render_results(loaded(result()))["results/index.md"]
    assert "| cesr\\-v1\\.0 |" in unknown


def test_a_profile_page_keeps_only_the_about_text_written_for_a_reader():
    generic = ("A profile is a named set of cases an implementation can claim: 'passes every "
               "active MUST assertion in profile P'. This file is generated by scripts/regenerate.")
    assert S._reader_about(generic) == ""
    specific = ("A profile is a named set of cases an implementation can claim: 'passes P', stated "
                "together with its SHOULD results. In this profile a MUST tests safety. This file "
                "is generated by scripts/regenerate.")
    assert S._reader_about(specific) == "In this profile a MUST tests safety."
    assert S._reader_about("A non-normative profile: escrow behaviour.") == "Escrow behaviour."
    page = S.render_profiles({"p": dict(PROFILES["cesr-v1.0"], name="p", about=generic)},
                             CASES)["profiles/p.md"]
    assert "This file" not in page and "named set" not in page


def test_a_profile_whose_name_cannot_be_a_path_is_refused(tmp_path):
    (tmp_path / "profiles").mkdir()
    (tmp_path / "profiles" / "x.json").write_text(json.dumps({"name": "../x", "cases": []}))
    with pytest.raises(RunnerError) as exc:
        S.load_profiles(tmp_path)
    assert exc.value.code == S.E_PROFILE_NAME


def test_the_real_profiles_render():
    profiles, cases = S.load_profiles(ROOT)
    pages = S.render_profiles(profiles, cases)
    assert "profiles/keri-v1.0.1.md" in pages and "profiles/keripy-1x-interop.md" in pages
    assert "features" not in profiles
